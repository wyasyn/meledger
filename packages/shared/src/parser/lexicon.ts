export interface Keyword {
  /** Words of the phrase. */
  words: readonly string[];
  categoryName: string;
}

function build(map: Record<string, readonly string[]>, kind: CategoryKind): Keyword[] {
  return Object.entries(map).flatMap(([name, phrases]) => {
    if (!CATEGORY_SEEDS.some((c) => c.name === name && c.kind === kind)) {
      throw new Error(`Parser keyword map names unknown ${kind} category "${name}"`);
    }
    return phrases.map((p) => ({ words: p.split(/[\s-]+/), categoryName: name }));
  });
}

